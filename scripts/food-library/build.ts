// Rebuilds the Forge food library from the pinned USDA releases.
//
//   npm run food-library:build            download if needed, verify, rebuild
//   npm run food-library:build -- --offline   use the cached archives only
//   npm run food-library:build -- --check     rebuild in memory and fail if the
//                                             committed outputs differ
//
// Archives are cached in .cache/food-library (gitignored) and verified
// against the SHA-256 and size pinned in sources.json before use. The
// outputs are deterministic: the same inputs and rules give the same bytes.
import { createHash } from "node:crypto";
import {
  existsSync,
  mkdirSync,
  readFileSync,
  renameSync,
  writeFileSync,
} from "node:fs";
import { basename, join } from "node:path";
import { listZip, readZipEntry } from "./zip";
import {
  curate,
  serializeCatalog,
  type CatalogFood,
  type SourceKey,
  type SourceSpec,
} from "./pipeline";
import { FAMILIES } from "./rules";
import { FEATURED } from "./featured";

const root = join(__dirname, "..", "..");
const cache = join(root, ".cache", "food-library");
const outDir = join(root, "src", "data", "food-library");
const reportDir = join(root, "docs", "food-library");
const args = process.argv.slice(2);
const offline = args.includes("--offline");
const check = args.includes("--check");
const MAX_JSON_BYTES = 300_000_000;

const config = JSON.parse(
  readFileSync(join(__dirname, "sources.json"), "utf8"),
) as { catalogVersion: string; attribution: string; sources: SourceSpec[] };

const sha256 = (b: Buffer | string) =>
  createHash("sha256").update(b).digest("hex");

async function archive(spec: SourceSpec) {
  const file = join(cache, basename(new URL(spec.url).pathname));
  if (!existsSync(file)) {
    if (offline) throw new Error(`${spec.key}: not cached (${file})`);
    console.log(`Downloading ${spec.url}`);
    const res = await fetch(spec.url);
    if (!res.ok) throw new Error(`${spec.url}: HTTP ${res.status}`);
    mkdirSync(cache, { recursive: true });
    const partial = `${file}.partial`;
    writeFileSync(partial, Buffer.from(await res.arrayBuffer()));
    renameSync(partial, file);
  }
  const bytes = readFileSync(file);
  if (bytes.length !== spec.bytes)
    throw new Error(`${spec.key}: ${bytes.length} bytes, pinned ${spec.bytes}`);
  const hash = sha256(bytes);
  if (hash !== spec.sha256)
    throw new Error(`${spec.key}: SHA-256 ${hash} does not match the pin`);
  const entries = listZip(bytes);
  const names = entries.map((e) => e.name);
  if (JSON.stringify(names) !== JSON.stringify(spec.members))
    throw new Error(
      `${spec.key}: unexpected archive members ${JSON.stringify(names)}`,
    );
  const json = JSON.parse(
    readZipEntry(bytes, entries[0]!, MAX_JSON_BYTES).toString("utf8"),
  ) as Record<string, unknown>;
  const records = json[spec.root];
  if (!Array.isArray(records))
    throw new Error(`${spec.key}: root "${spec.root}" is not an array`);
  return records as unknown[];
}

function count<T>(rows: T[], key: (r: T) => string) {
  const m: Record<string, number> = {};
  for (const r of rows) m[key(r)] = (m[key(r)] ?? 0) + 1;
  return Object.fromEntries(
    Object.entries(m).sort(([a], [b]) => a.localeCompare(b, "en")),
  );
}

function quality(foods: CatalogFood[]) {
  const zero = (k: "protein" | "carbs" | "fat" | "kcal") =>
    foods.filter((f) => f.per100[k] === 0).length;
  return {
    energyNutrientIds: count(foods, (f) => String(f.energyId)),
    sourceReportedZero: {
      kcal: zero("kcal"),
      protein: zero("protein"),
      carbs: zero("carbs"),
      fat: zero("fat"),
    },
    withHouseholdPortions: foods.filter((f) => f.portions.length).length,
    householdPortions: foods.reduce((n, f) => n + f.portions.length, 0),
  };
}

function report(
  foods: CatalogFood[],
  exclusions: ReturnType<typeof curate>["exclusions"],
  manifest: Record<string, unknown>,
) {
  const lines = [
    "# Forge food library: build report",
    "",
    "_Generated by `npm run food-library:build`. Do not edit by hand._",
    "",
    `Catalog ${config.catalogVersion}: **${foods.length} foods**. See [manifest.json](../../src/data/food-library/manifest.json) for hashes and [PHASE_7B_WP4A1_FOOD_LIBRARY_PLAN.md](../audits/PHASE_7B_WP4A1_FOOD_LIBRARY_PLAN.md) for the rules.`,
    "",
    "## Coverage by family",
    "",
    "| Family | FNDDS | SR Legacy | Total |",
    "| --- | ---: | ---: | ---: |",
    ...FAMILIES.map((f) => {
      const n = (s: SourceKey) =>
        foods.filter((x) => x.family === f && x.source === s).length;
      return `| ${f} | ${n("fndds")} | ${n("sr")} | ${n("fndds") + n("sr")} |`;
    }),
    "",
    "## Exclusions by reason",
    "",
    "| Reason | FNDDS | SR Legacy |",
    "| --- | ---: | ---: |",
    ...Object.keys(count(exclusions, (e) => e.reason)).map((reason) => {
      const n = (s: SourceKey) =>
        exclusions.filter((e) => e.reason === reason && e.source === s).length;
      return `| ${reason} | ${n("fndds")} | ${n("sr")} |`;
    }),
    "",
    "Every excluded record except SR Legacy records outside the allowlist is listed in [exclusions.tsv](exclusions.tsv).",
    "",
    "## Quality",
    "",
    "```json",
    JSON.stringify(manifest.quality, null, 2),
    "```",
    "",
  ];
  const tsv = [
    "id\treason\tdescription",
    ...exclusions
      .filter((e) => e.reason !== "sr-not-in-allowlist")
      .map((e) => `${e.id}\t${e.reason}\t${e.description}`),
  ].join("\n");
  return { md: `${lines.join("\n")}`, tsv: `${tsv}\n` };
}

async function main() {
  const inputs = [];
  for (const spec of config.sources)
    inputs.push({ spec, records: await archive(spec) });
  const { foods, exclusions, inputs: counts } = curate(inputs);

  const ids = new Set(foods.map((f) => f.id));
  const missing = FEATURED.filter((id) => !ids.has(id));
  if (missing.length)
    throw new Error(`Featured foods not in the catalog: ${missing.join(", ")}`);

  const releases = Object.fromEntries(
    config.sources.map((s) => [s.key, `${s.label} (${s.release})`]),
  ) as Record<SourceKey, string>;
  const catalog = serializeCatalog(
    config.catalogVersion,
    releases,
    foods,
    FEATURED,
  );
  const manifest = {
    generatedBy: "scripts/food-library/build.ts",
    formatVersion: 1,
    catalogVersion: config.catalogVersion,
    attribution: config.attribution,
    catalog: {
      file: "src/data/food-library/catalog.json",
      bytes: Buffer.byteLength(catalog),
      sha256: sha256(catalog),
      foods: foods.length,
      featured: FEATURED.length,
    },
    sources: config.sources.map((s) => ({
      key: s.key,
      label: s.label,
      dataType: s.dataType,
      release: s.release,
      url: s.url,
      sha256: s.sha256,
      bytes: s.bytes,
      records: counts[s.key],
      included: foods.filter((f) => f.source === s.key).length,
      energyNutrientIds: s.energyNutrientIds,
    })),
    families: count(foods, (f) => f.family),
    exclusions: {
      total: exclusions.length,
      byReason: count(exclusions, (e) => `${e.source}: ${e.reason}`),
    },
    quality: quality(foods),
  };
  const { md, tsv } = report(foods, exclusions, manifest);
  const outputs: [string, string][] = [
    [join(outDir, "catalog.json"), catalog],
    // The bundled form: the same JSON as one string (see food-catalog.ts).
    [
      join(outDir, "catalog.js"),
      `// Generated by \`npm run food-library:build\` from catalog.json. Do not edit.\nmodule.exports = ${JSON.stringify(catalog)};\n`,
    ],
    [join(outDir, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`],
    [join(reportDir, "BUILD_REPORT.md"), md],
    [join(reportDir, "exclusions.tsv"), tsv],
  ];
  if (check) {
    const stale = outputs.filter(
      ([file, text]) =>
        !existsSync(file) || readFileSync(file, "utf8") !== text,
    );
    if (stale.length) {
      console.error(
        `Food library outputs differ from a fresh build:\n  ${stale.map(([f]) => f).join("\n  ")}`,
      );
      process.exit(1);
    }
    console.log(
      `Food library is reproducible: ${foods.length} foods, catalog ${manifest.catalog.sha256}`,
    );
    return;
  }
  mkdirSync(outDir, { recursive: true });
  mkdirSync(reportDir, { recursive: true });
  for (const [file, text] of outputs) writeFileSync(file, text);
  console.log(
    `Wrote ${foods.length} foods (${manifest.catalog.bytes} bytes, sha256 ${manifest.catalog.sha256}).`,
  );
  console.log(JSON.stringify(manifest.families));
}

main().catch((e: unknown) => {
  console.error(e instanceof Error ? e.message : e);
  process.exit(1);
});
